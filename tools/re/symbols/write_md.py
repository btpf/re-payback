"""Step 3 of 3: generate docs/xref/symbols.md from outputs.pkl (+ the hand-written symbols_tail.md)."""
import pickle, os, collections, re
import load, match

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', '..', 'docs', 'xref', 'symbols.md')
O = pickle.load(open(os.path.join(load.CACHE, 'outputs.pkl'), 'rb'))
rows = O['rows']; amiga_only = O['amiga_only']; cites = O['cites']
A = load.parse('mac')['funcs']; B = load.parse('os4')['funcs']; C = load.parse('m68k')['funcs']

L = []
w = L.append
cat = collections.Counter(r['cat'] for r in rows)
matched = [r for r in rows if r['os4_addr'] or r['m68k_addr']]
game = [r for r in rows if r['cat'] == 'game']
game_m = [r for r in game if r['os4_addr'] or r['m68k_addr']]
conf = collections.Counter(r['confidence'] for r in matched)
os4g = [b for b in B if match.os4_region(b) != 'libc']
m_os4 = {r['os4_addr'] for r in rows if r['os4_addr']}
c68g = [c for c in C if match.m68k_region(c) != 'libc']
m_68 = {r['m68k_addr'] for r in rows if r['m68k_addr']}

doc_os4 = sorted(k for k in cites if k.startswith('01'))
doc_68k = sorted(k for k in cites if k.startswith('00'))
by_os4 = {r['os4_addr']: r for r in rows if r['os4_addr']}
by_68k = {r['m68k_addr']: r for r in rows if r['m68k_addr']}
res_os4 = [k for k in doc_os4 if k in by_os4]
res_68k = [k for k in doc_68k if k in by_68k]

w('# Mac symbol cross-reference (Mac OS X build names for the Amiga `FUN_` addresses)')
w('')
w('Generated by `tools/re/symbols/` (`final_match.py`, `build_outputs.py`, `write_md.py`; the last section is')
w('hand-written, in `tools/re/symbols/symbols_tail.md`).')
w('Full table: `docs/xref/symbols.tsv` (one row per Mac function, then OS4 game functions with')
w('no Mac counterpart). Mac names are the CodeWarrior traceback names of `Payback (OS X)`')
w('(`analysis/ghidra_macx`). OS4 = `analysis/ghidra_os4` (`FUN_010xxxxx`), 68k = Update 7')
w('`analysis/ghidra_68k` (`FUN_000xxxxx`).')
w('')
w('## Counts')
w('')
w(f'- Mac functions: {len(rows)} — game code {cat["game"]}, PowerPlant/runtime {cat["powerplant"]}, '
  f'Mac classes {cat["mac-class"]}, Amiga-API shims {cat["amiga-shim"]}, Mac glue (`amiga_*`) {cat["mac-glue"]}, '
  f'MSL runtime {cat["msl-runtime"]}, imports {cat["import"]}.')
w(f'- **Matched to an Amiga function: {len(matched)}** ({sum(1 for r in rows if r["os4_addr"])} with an OS4 address, '
  f'{sum(1 for r in rows if r["m68k_addr"])} with a 68k address). Confidence: high {conf["high"]}, '
  f'medium {conf["medium"]}, low {conf["low"]}.')
w(f'- Game functions (mangled `__F` names in the game ranges): {len(game_m)} of {len(game)} matched.')
w(f'- OS4 non-runtime functions: {len(set(os4g) & m_os4)} of {len(os4g)} have a Mac name; '
  f'{len(amiga_only)} have none (listed below). The 215 clib2 runtime functions are not matched except where noted.')
w(f'- 68k non-runtime functions: {len(set(c68g) & m_68)} of {len(c68g)} have a Mac name.')
w(f'- `FUN_` addresses cited in `docs/`: OS4 {len(res_os4)} of {len(doc_os4)} resolved, 68k {len(res_68k)} of {len(doc_68k)} resolved.')
w('')
w('## Method')
w('')
w('Three pairwise matchers (Mac↔OS4, OS4↔68k, Mac↔68k), then triangulation:')
w('')
w('1. **Strings.** Mac string references go through the TOC, so `pef.py` unpacks the PEF data')
w('   section, applies the loader relocations and resolves `_DAT_1017xxxx` TOC slots (plus')
w('   `slot + offset` and `var = slot; ... var + offset` forms) to C strings. Unique shared strings seed the match.')
w('2. **Call graph.** For every matched pair the ordered callee lists are aligned (matched callees as')
w('   anchors); unmatched callees in aligned slots, and lone unmatched callers, become candidates.')
w('   Calls into the Mac Amiga-API shims and PowerPlant are dropped first (on the Amiga those are')
w('   library-vector calls, not functions).')
w('3. **Similarity** = size (68k scaled by 0.68), callee count, branch/loop counts, non-trivial constants,')
w('   agreement of already-matched callers/callees, and agreement of global-data references (Mac TOC')
w('   targets ↔ Amiga `DAT_` addresses, learned from the matches so far).')
w('4. **Address order.** CodeWarrior and GCC both emit functions in source order, so runs of unmatched')
w('   functions between two order-consistent anchors (and after/before section breaks) are aligned')
w('   by dynamic programming. Weak matches that disagree with their neighbours\' order are dropped or')
w('   re-pointed to an order-consistent twin.')
w('5. **Triangulation.** Matches on which all three pairings agree are re-used as anchors for two')
w('   more rounds; remaining Mac→OS4→68k vs Mac→68k conflicts between sibling functions are')
w('   resolved by majority (evidence `triangle-swap`).')
w('6. **Manual anchors** (evidence `manual:`): the mission-script dispatchers (`InitScript__Fii`,')
w('   `ProcessTrigger__Fi`) were read side by side to map `InitScript_NN` / `ProcessTrigger_NN`; the')
w('   route-table API uses the roles already documented in `docs/re/combat_police.md`.')
w('')
w('Confidence: **high** = unique strings, or strong call-graph evidence with order agreement and')
w('(usually) all three builds agreeing; **medium** = one strong signal; **low** = shape/position only.')
w('Tiny accessors (≤ 24 bytes) matched only by position are capped at medium: neighbouring')
w('getters/setters are interchangeable to the matcher. MSL↔clib2 runtime pairs are shape-only (low).')
w('')

# ---- doc table
w('## Functions cited in `docs/` with their Mac names')
w('')
w('Sorted by OS4 address; 68k-only citations follow. "Docs" lists the notes that cite the OS4 or 68k address.')
w('')
w('| Mac name | Mac addr | OS4 | 68k | Conf. | Docs |')
w('|---|---|---|---|---|---|')
seen = set()


def short(fs):
    return ', '.join(f.replace('.md', '') for f in fs)


def emit(r):
    key = r['mac_addr']
    if key in seen:
        return
    seen.add(key)
    ds = sorted(set(cites.get(r['os4_addr'], [])) | set(cites.get(r['m68k_addr'], [])))
    dm = r['demangled'].replace('|', '\\|')
    w(f"| `{dm}` | `{r['mac_addr']}` | {('`' + r['os4_addr'] + '`') if r['os4_addr'] else '—'} | "
      f"{('`' + r['m68k_addr'] + '`') if r['m68k_addr'] else '—'} | {r['confidence']} | {short(ds)} |")


for k in res_os4:
    emit(by_os4[k])
for k in res_68k:
    emit(by_68k[k])
w('')

# ---- unresolved doc citations
w('### Cited addresses without a Mac name')
w('')
ao = {r['os4_addr']: r for r in amiga_only}
r_ok = {c: b for b, c in O['ok'].items()}
w('| Address | Size | Other build | Notes (strings / docs) |')
w('|---|---|---|---|')
for k in doc_os4:
    if k in by_os4:
        continue
    f = B.get(k)
    other = O['ok'].get(k, '')
    hint = '; '.join(sorted(f['strings'])[:2]) if f else 'not a function start'
    hint = hint.replace('|', '/').replace('\n', ' ')[:90]
    w(f"| OS4 `{k}` | {f['size'] if f else ''} | {('68k `' + other + '`') if other else '—'} | {hint} ({short(cites[k])}) |")
for k in doc_68k:
    if k in by_68k:
        continue
    f = C.get(k)
    other = r_ok.get(k, '')
    hint = '; '.join(sorted(f['strings'])[:2]) if f else 'not a function start'
    hint = hint.replace('|', '/').replace('\n', ' ')[:90]
    w(f"| 68k `{k}` | {f['size'] if f else ''} | {('OS4 `' + other + '`') if other else '—'} | {hint} ({short(cites[k])}) |")
w('')
part2 = open(os.path.join(HERE, 'symbols_tail.md'), encoding='utf-8').read()
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(L) + '\n' + part2)

# lists for the hand-written sections
new_game = [r for r in game if not (r['os4_addr'] or r['m68k_addr'])]
open(os.path.join(load.CACHE, 'new_game.txt'), 'w', encoding='utf-8', newline='\n').write(
    '\n'.join(f"{r['mac_addr']}\t{r['size']}\t{r['demangled']}" for r in new_game) + '\n')
glue = [r for r in rows if r['cat'] in ('mac-glue', 'amiga-shim', 'mac-class', 'other')]
open(os.path.join(load.CACHE, 'mac_glue.txt'), 'w', encoding='utf-8', newline='\n').write(
    '\n'.join(f"{r['mac_addr']}\t{r['size']}\t{r['cat']}\t{r['demangled']}\t{r['os4_addr']}" for r in glue) + '\n')
print('doc rows', len(seen), 'new game', len(new_game))
